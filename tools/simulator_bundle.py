"""Write docs/simulator/bundle.js: the Python the simulator page runs in Pyodide, as strings.

The page loads it with a <script> tag, so it works from a file opened locally (a browser fetches
no file:// URL). It holds the page's own modules (docs/simulator/*.py), the invented house's
``model.py`` and ``devices.py``, and every module of the integration those import, found by
following their imports. Each of those must be in ``tools/import_bounds.py``'s ``STDLIB_ONLY``:
the page has no Home Assistant. The integration's own ``__init__.py`` sets up Home Assistant, so
the bundle gives the package an empty one (``PACKAGE_INIT``); the invented house's gets the same.

    python3 tools/simulator_bundle.py           write the bundle
    python3 tools/simulator_bundle.py --check   exit 1 if the bundle is not what it would write
    python3 tools/simulator_bundle.py --tree D  write the bundle's files under directory D

tests/test_simulator.py runs ``--check`` and runs the page's Python from a ``--tree`` with every
``homeassistant`` import refused.
"""

from __future__ import annotations

import ast
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "tools"))

from import_bounds import PACKAGE, SOURCE, STDLIB_ONLY

PAGE = ROOT / "docs" / "simulator"
BUNDLE = PAGE / "bundle.js"
HOUSE = ROOT / "verification" / "instance" / "invented_house"
HOUSE_MODULES = ("model", "devices")
PACKAGE_DIR = "custom_components/mxz_coordinator"
PACKAGE_INIT = (
    '"""The simulator\'s stand-in for the package\'s __init__.py, which sets up Home Assistant.\n\n'
    "The page loads only the integration's modules that import no Home Assistant\n"
    '(tools/simulator_bundle.py)."""\n'
)
HOUSE_INIT = (
    '"""The simulator\'s stand-in for invented_house/__init__.py, which sets up Home Assistant.\n\n'
    'The page loads only model.py and devices.py (tools/simulator_bundle.py)."""\n'
)
HEADER = (
    "// Generated by tools/simulator_bundle.py from the files it names. Do not edit;\n"
    "// run `python3 tools/simulator_bundle.py` after changing any of them.\n"
)


def _imported(path: Path) -> set[str]:
    """The integration modules ``path`` imports, by module name."""
    tree = ast.parse(path.read_text(encoding="utf-8"))
    found: set[str] = set()
    inside = path.parent == SOURCE
    for node in ast.walk(tree):
        if isinstance(node, ast.ImportFrom):
            if node.level == 1 and inside:
                if node.module is None:
                    found.update(alias.name for alias in node.names)
                else:
                    found.add(node.module.split(".")[0])
            elif node.level == 0 and node.module is not None:
                if node.module == PACKAGE:
                    found.update(alias.name for alias in node.names)
                elif node.module.startswith(PACKAGE + "."):
                    found.add(node.module.removeprefix(PACKAGE + ".").split(".")[0])
        elif isinstance(node, ast.Import):
            for alias in node.names:
                if alias.name.startswith(PACKAGE + "."):
                    found.add(alias.name.removeprefix(PACKAGE + ".").split(".")[0])
    return found


def page_modules() -> list[Path]:
    return sorted(PAGE.glob("*.py"))


def integration_modules() -> list[str]:
    """Every integration module the page's Python reaches, sorted. Raises if one is not
    standard library only."""
    seen: set[str] = set()
    todo = set().union(*(_imported(path) for path in page_modules()))
    while todo:
        name = todo.pop()
        if name in seen:
            continue
        if name not in STDLIB_ONLY:
            raise SystemExit(f"{name} is not in STDLIB_ONLY: the page cannot load it")
        seen.add(name)
        todo |= _imported(SOURCE / f"{name}.py") - seen
    return sorted(seen)


def files() -> dict[str, str]:
    """Each bundled file by its path in the page's file system, in a fixed order."""
    out: dict[str, str] = {}
    for path in page_modules():
        out[path.name] = path.read_text(encoding="utf-8")
    out["custom_components/__init__.py"] = ""
    out[f"{PACKAGE_DIR}/__init__.py"] = PACKAGE_INIT
    for name in integration_modules():
        out[f"{PACKAGE_DIR}/{name}.py"] = (SOURCE / f"{name}.py").read_text(encoding="utf-8")
    out["invented_house/__init__.py"] = HOUSE_INIT
    for name in HOUSE_MODULES:
        out[f"invented_house/{name}.py"] = (HOUSE / f"{name}.py").read_text(encoding="utf-8")
    out["invented_house/house.json"] = (HOUSE / "house.json").read_text(encoding="utf-8")
    return out


def render() -> str:
    body = json.dumps(files(), indent=1, ensure_ascii=False)
    return f"{HEADER}window.MXZ_SIMULATOR_FILES = {body};\n"


def write_tree(target: Path) -> None:
    for name, text in files().items():
        path = target / name
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8")


def main(argv: list[str]) -> int:
    if argv[:1] == ["--check"]:
        if not BUNDLE.exists() or BUNDLE.read_text(encoding="utf-8") != render():
            print(f"{BUNDLE.relative_to(ROOT)} is stale: run python3 tools/simulator_bundle.py")
            return 1
        return 0
    if argv[:1] == ["--tree"] and len(argv) == 2:
        write_tree(Path(argv[1]))
        return 0
    if argv:
        print(__doc__)
        return 2
    BUNDLE.write_text(render(), encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
